"""A held-out term list, for auditing the target rather than building it.

`phenotype_gap_audit.py` asks whether the target finds the terms a clinician
would write, and it can only answer that against a list the target had no hand
in. Every list already in the pipeline fails that test: the anchors were
proposed for the target, the associated terms were recovered into it, and the
concept sets are the thing being audited.

So this writes a new one, and three choices keep it honest:

* **A third model.** The anchors came from `gpt-5.6-luna` and were reviewed by
  `gpt-5.6-terra`. This asks `gpt-5.6-sol`, which contributed to neither, so a
  gap cannot be explained away as one model disagreeing with itself.
* **A different question.** The anchor prompt asked for the ways a diagnosis is
  *written*. This asks what a reader would find in a discharge summary that
  tells them the patient has the condition — which admits findings, values and
  treatments, not just names, and is therefore a harder test than the one the
  anchors were built to pass.
* **Written before the result is known, and kept.** The list is committed, so a
  later run cannot quietly regenerate a friendlier one.

It lives here rather than in RobustEHR because which terms a clinician writes is
a property of a corpus and a specialty, and the package has not measured that.
A study supplies its own.

Usage::

    export OPENROUTER_API_KEY=...
    cd experiments/exp3_corrected
    python heldout_terms.py --out heldout_terms.tsv
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
import urllib.request
from pathlib import Path

ENDPOINT = "https://openrouter.ai/api/v1/chat/completions"
DEFAULT_MODEL = "openai/gpt-5.6-sol"
DEFAULT_CACHE = Path("data/llm_cache")

PROMPT = """You are listing what a discharge summary actually contains when a patient
has a given condition.

CONDITION: {label}

List the distinct pieces of text a physician reading the note would use to
decide this patient has this condition. Include:
- the diagnosis written the ways clinicians write it, including abbreviations
- characteristic examination findings
- imaging or laboratory findings that would be reported
- treatments that would only be given for this condition
- complications that imply it

Each line is a phrase as it would appear in a note, lowercase, no explanation.
Write phrases a clinician would actually type, not textbook headings. Aim for
25 to 40 lines. One per line, nothing else.
"""


def complete(model: str, key: str, cache: Path, prompt: str) -> str:
    digest = hashlib.blake2b(f"{model}\x1f{prompt}".encode(), digest_size=16).hexdigest()
    hit = cache / f"heldout-{digest}.json"
    if hit.exists():
        return str(json.loads(hit.read_text(encoding="utf-8"))["choices"][0]["message"]["content"])
    body = json.dumps(
        {
            "model": model,
            "temperature": 0,
            "provider": {"data_collection": "deny"},
            "messages": [{"role": "user", "content": prompt}],
        }
    ).encode("utf-8")
    request = urllib.request.Request(
        ENDPOINT,
        data=body,
        headers={"Authorization": f"Bearer {key}", "Content-Type": "application/json"},
    )
    with urllib.request.urlopen(request, timeout=180) as response:
        payload = json.load(response)
    if "choices" not in payload:
        raise RuntimeError(str(payload)[:200])
    cache.mkdir(parents=True, exist_ok=True)
    hit.write_text(json.dumps(payload, sort_keys=True), encoding="utf-8")
    return str(payload["choices"][0]["message"]["content"])


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--model", default=DEFAULT_MODEL)
    parser.add_argument("--cache", type=Path, default=DEFAULT_CACHE)
    parser.add_argument("--cohort", default="mipa")
    args = parser.parse_args(argv)

    key = os.environ.get("OPENROUTER_API_KEY", "").strip()
    if not key:
        print("set OPENROUTER_API_KEY", file=sys.stderr)
        return 2

    from robustehr.concepts.phenotype import in_cohort, load_definitions

    definitions = load_definitions()
    names = sorted(in_cohort(args.cohort))

    lines = [
        "# Held-out clinical terms for phenotype_gap_audit.py.",
        f"# Generated by {args.model}, which built none of the target's resources.",
        "# Asked what a note CONTAINS, not how the diagnosis is written, so it",
        "# tests more than the anchor lists were built to cover.",
        "# phenotype<TAB>term",
    ]
    for name in names:
        reply = complete(args.model, key, args.cache, PROMPT.format(label=definitions[name].label))
        seen: dict[str, None] = {}
        for raw in reply.splitlines():
            term = " ".join(raw.strip().strip("-*•").strip().lower().split())
            if term[:1].isdigit() and "." in term[:4]:
                term = term.split(".", 1)[1].strip()
            if len(term) < 4 or len(term) > 70 or term.endswith(":"):
                continue
            seen.setdefault(term, None)
        print(f"  {name:32s} {len(seen)} terms")
        lines += [f"{name}\t{t}" for t in seen]

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\n{args.out}: {len(lines) - 5} terms over {len(names)} phenotypes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
